"""Build media-meta.js for the works page (index.html).

For every media file shown inline (first 4 of each work) it records the file's pixel size, so tiles get
their final size before anything downloads (no layout shift), and for the
images it writes smaller copies next to the original:
  <name>.w640.webp, <name>.w1280.webp
which index.html offers through srcset (the lightbox keeps the full file).

Also refreshes the ?v= versions of works.js / media-meta.js in index.html.

Run again after adding works:   py -3.11 tools/build_media_meta.py
"""
import hashlib, json, os, re, subprocess, sys, time
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TIERS = (640, 1280)
INLINE = 4  # index.html shows up to 4 media per work inline (2 on phones)

src = open(os.path.join(ROOT, 'works.js'), encoding='utf8').read()
works = re.findall(r'media:\s*\[(.*?)\]', src, re.S)
meta, made = {}, 0


def tier_path(path, w):
    return re.sub(r'\.[^./]+$', '', path) + f'.w{w}.webp'


def video_size(path):
    # the clip itself (posters are smaller encodes, not the clip's size)
    out = subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries',
                          'stream=width,height', '-of', 'csv=p=0', os.path.join(ROOT, path)],
                         capture_output=True, text=True).stdout.strip()
    return tuple(int(x) for x in out.split(',')[:2]) if out else None


for block in works:
    for i, entry in enumerate(re.findall(r'"([^"]+)"', block)):
        flags = set()
        while (m := re.match(r'(video|light|bleed):', entry)):
            flags.add(m.group(1)); entry = entry[m.end():]
        if i >= INLINE: break  # the rest only open in the lightbox (full file, size not needed)
        full = os.path.join(ROOT, entry)
        if entry in meta or not os.path.exists(full):
            if not os.path.exists(full): print('missing:', entry, file=sys.stderr)
            continue
        if 'video' in flags:
            size = video_size(entry)
            if size: meta[entry] = list(size)
            continue
        with Image.open(full) as im:
            w, h = im.size
            animated = getattr(im, 'is_animated', False)
            tiers = []
            if not animated:
                for tw in TIERS:
                    if w < tw * 1.25: break  # original is already about this size
                    out = os.path.join(ROOT, tier_path(entry, tw))
                    if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(full):
                        frame = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB')
                        frame.resize((tw, round(h * tw / w)), Image.LANCZOS).save(out, 'WEBP', quality=82, method=6)
                        made += 1
                    tiers.append(tw)
        meta[entry] = [w, h] + ([tiers] if tiers else [])

with open(os.path.join(ROOT, 'media-meta.js'), 'w', encoding='utf8', newline='\n') as f:
    f.write('// Generated by tools/build_media_meta.py - pixel size of each works.js media file\n'
            '// [width, height, (smaller .wN.webp copies)]. Re-run that script after adding works.\n')
    f.write('window.FLUXUS_MEDIA = ' + json.dumps(meta, ensure_ascii=False, separators=(',', ':')) + ';\n')
# index.html loads both data files with ?v=<content hash>, so a deploy is picked up right away
ix = os.path.join(ROOT, 'index.html')
page = open(ix, encoding='utf8').read()
for name in ('works.js', 'media-meta.js'):
    v = hashlib.md5(open(os.path.join(ROOT, name), 'rb').read()).hexdigest()[:8]
    page = re.sub(re.escape(name) + r'\?v=[0-9a-f]+', f'{name}?v={v}', page)
for attempt in range(20):  # an editor / sync tool can hold the file for a moment
    try:
        open(ix, 'w', encoding='utf8', newline='\n').write(page); break
    except OSError:
        if attempt == 19: raise
        time.sleep(0.5)
print(f'{len(meta)} entries, {made} thumbnails written, index.html versions updated')
